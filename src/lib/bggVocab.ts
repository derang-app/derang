/** BGG terms that also earn one of the app's broad tags used by «چی بازی کنیم؟». */
const BROAD: Record<string, string> = {
  'Abstract Strategy': 'فکری',
  Deduction: 'فکری',
  Puzzle: 'فکری',
};

const sortFa = (list: string[]) => [...new Set(list)].sort((a, b) => a.localeCompare(b, 'fa'));
export const CATEGORY_TAGS = sortFa(Object.values(BGG_CATEGORIES));
export const MECHANIC_TAGS = sortFa(Object.values(BGG_MECHANICS).filter((t) => !CATEGORY_TAGS.includes(t)));

/** The app's tags for a game's BGG categories, mechanics and rank families. */
export function bggTags(categories: string[], mechanics: string[], families: string[]): string[] {
  // Either list may hold a term of the other kind (BGG has moved some over the years).
  const fa = (t: string) => BGG_CATEGORIES[t] ?? BGG_MECHANICS[t] ?? t;
  const out = [
    ...[...categories, ...mechanics].map(fa),
    ...families.map((f) => BGG_FAMILIES[f]),
    ...[...categories, ...mechanics].map((t) => BROAD[t]),
  ];
  return [...new Set(out.filter((t): t is string => !!t))];
}
